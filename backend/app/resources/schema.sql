    -- 真练真会 · 建表脚本（PostgreSQL 16）
    -- 执行方式：psql -U <用户名> -d <数据库名> -f db/schema.sql
    -- 约定：
    --   1. 时间用 timestamptz，由后端生成。接口上传出去时转成 2026-11-25T16:20:30+08:00 这种写法。
    --   2. 数组类字段用 jsonb，由后端解析。每张表都加了「必须是 JSON 数组」的检查。
    --   3. 布尔值用 boolean。
    --   4. 删一张卷时，它下面的题、学习作答、考试、错题、对话一起删（见各表的外键）。
    --   5. scene 表示「在哪儿做的」：paper 普通卷里，wrongbook 错题本里。

    -- 1. 试卷
    CREATE TABLE paper (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title       TEXT        NOT NULL,
        year        INTEGER,
        kind        TEXT        NOT NULL DEFAULT 'exam' CHECK (kind IN ('exam', 'custom')),
        status      TEXT        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
        created_at  TIMESTAMPTZ NOT NULL,
        updated_at  TIMESTAMPTZ NOT NULL
    );

    -- 2. 上传解析任务。一次上传对应一张新卷，所以 paper_id 唯一。
    CREATE TABLE import_job (
        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        paper_id       BIGINT      NOT NULL UNIQUE REFERENCES paper(id) ON DELETE CASCADE,
        file_name      TEXT        NOT NULL,
        stored_path    TEXT        NOT NULL,
        file_type      TEXT        NOT NULL CHECK (file_type IN ('pdf', 'png', 'jpg', 'webp')),
        status         TEXT        NOT NULL DEFAULT 'pending'
                                   CHECK (status IN ('pending', 'processing', 'waiting_review', 'completed', 'failed', 'cancelled')),
        stage          TEXT        CHECK (stage IN ('extract', 'segment', 'structure', 'generate_answer')),
        has_answer     TEXT        CHECK (has_answer IN ('yes', 'no', 'mixed')),
        question_count INTEGER,
        error_message  TEXT,
        created_at     TIMESTAMPTZ NOT NULL,
        started_at     TIMESTAMPTZ,
        finished_at    TIMESTAMPTZ
    );

    -- 3. 题目。status = draft 的题只在审核页出现，确认后改成 approved。
    --    一道题的题干、题干图片、选项、选项图片都在这一行里，接口原样拼成一个对象返回。
    --    答案是文档里提取的还是 AI 生成的，不记录。
    CREATE TABLE question (
        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        paper_id       BIGINT      NOT NULL REFERENCES paper(id) ON DELETE CASCADE,
        seq_no         INTEGER     NOT NULL,
        qtype          TEXT        NOT NULL CHECK (qtype IN ('single', 'multi', 'judge', 'short', 'calc')),
        subject        TEXT        NOT NULL,
        score          INTEGER     NOT NULL CHECK (score > 0),
        stem           TEXT        NOT NULL,
        stem_images    JSONB       NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(stem_images) = 'array'),
        options        JSONB       NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(options) = 'array'),
        parts          JSONB       CHECK (parts IS NULL OR jsonb_typeof(parts) = 'array'),
        answer_choice  JSONB       CHECK (answer_choice IS NULL OR jsonb_typeof(answer_choice) = 'array'),
        answer_text    TEXT,
        analysis       TEXT,
        knowledge_tags JSONB       NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(knowledge_tags) = 'array'),
        status         TEXT        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved')),
        import_job_id  BIGINT      REFERENCES import_job(id) ON DELETE SET NULL,
        created_at     TIMESTAMPTZ NOT NULL,
        updated_at     TIMESTAMPTZ NOT NULL,
        UNIQUE (paper_id, seq_no)
    );
    CREATE INDEX idx_question_paper_status ON question(paper_id, status);

    -- 4. 每张卷的学习进度（只记普通卷里的）
    CREATE TABLE study_progress (
        paper_id        BIGINT      PRIMARY KEY REFERENCES paper(id) ON DELETE CASCADE,
        current_seq     INTEGER     NOT NULL,
        last_studied_at TIMESTAMPTZ
    );

    -- 5. 学习作答。一道题在一个地方一行；错题本里的作答和普通卷里的分开。
    CREATE TABLE study_answer (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        question_id BIGINT      NOT NULL REFERENCES question(id) ON DELETE CASCADE,
        scene       TEXT        NOT NULL DEFAULT 'paper' CHECK (scene IN ('paper', 'wrongbook')),
        choice      JSONB       CHECK (choice IS NULL OR jsonb_typeof(choice) = 'array'),
        is_correct  BOOLEAN,
        is_done     BOOLEAN     NOT NULL DEFAULT FALSE,
        is_marked   BOOLEAN     NOT NULL DEFAULT FALSE,
        updated_at  TIMESTAMPTZ NOT NULL,
        UNIQUE (question_id, scene)
    );

    -- 6. 每日学习时长（秒）。study_date 是本地日期。
    CREATE TABLE study_time_daily (
        study_date DATE    PRIMARY KEY,
        seconds    INTEGER NOT NULL DEFAULT 0 CHECK (seconds >= 0)
    );

    -- 7. 一场考试。没有「暂停」这个状态：考试中只要离开考试界面就作废。
    CREATE TABLE exam_attempt (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        paper_id         BIGINT      NOT NULL REFERENCES paper(id) ON DELETE CASCADE,
        duration_sec     INTEGER     NOT NULL CHECK (duration_sec > 0),
        status           TEXT        NOT NULL DEFAULT 'in_progress'
                                     CHECK (status IN ('in_progress', 'submitted', 'auto_submitted', 'abandoned')),
        started_at       TIMESTAMPTZ NOT NULL,
        deadline_at      TIMESTAMPTZ NOT NULL,
        submitted_at     TIMESTAMPTZ,
        elapsed_sec      INTEGER,
        objective_score  INTEGER,
        subjective_score INTEGER,
        total_score      INTEGER,
        created_at       TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX idx_exam_attempt_paper ON exam_attempt(paper_id, started_at DESC);

    -- 8. 一场考试里每道题的作答
    CREATE TABLE exam_answer (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        attempt_id  BIGINT      NOT NULL REFERENCES exam_attempt(id) ON DELETE CASCADE,
        question_id BIGINT      NOT NULL REFERENCES question(id) ON DELETE CASCADE,
        choice      JSONB       CHECK (choice IS NULL OR jsonb_typeof(choice) = 'array'),
        is_done     BOOLEAN     NOT NULL DEFAULT FALSE,
        self_score  INTEGER     CHECK (self_score IS NULL OR self_score >= 0),
        is_marked   BOOLEAN     NOT NULL DEFAULT FALSE,
        is_correct  BOOLEAN,
        updated_at  TIMESTAMPTZ NOT NULL,
        UNIQUE (attempt_id, question_id)
    );

    -- 9. 错题本条目。移除就是删这一行。
    CREATE TABLE wrong_item (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        question_id BIGINT      NOT NULL UNIQUE REFERENCES question(id) ON DELETE CASCADE,
        created_at  TIMESTAMPTZ NOT NULL
    );

    -- 10. 对话。一道题在一个地方一段对话。
    CREATE TABLE chat_thread (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        question_id BIGINT      NOT NULL REFERENCES question(id) ON DELETE CASCADE,
        scene       TEXT        NOT NULL DEFAULT 'paper' CHECK (scene IN ('paper', 'wrongbook')),
        created_at  TIMESTAMPTZ NOT NULL,
        updated_at  TIMESTAMPTZ NOT NULL,
        UNIQUE (question_id, scene)
    );

    -- 11. 对话里的一句话
    CREATE TABLE chat_message (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        thread_id  BIGINT      NOT NULL REFERENCES chat_thread(id) ON DELETE CASCADE,
        role       TEXT        NOT NULL CHECK (role IN ('user', 'assistant')),
        mode       TEXT        CHECK (mode IN ('guide', 'learn')),
        content    TEXT        NOT NULL,
        created_at TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX idx_chat_message_thread ON chat_message(thread_id, id);

    -- 12. 设置。api_key 的 value 存加密后的密文，is_encrypted 为 true。
    CREATE TABLE app_setting (
        key          TEXT        PRIMARY KEY,
        value        TEXT        NOT NULL,
        is_encrypted BOOLEAN     NOT NULL DEFAULT FALSE,
        updated_at   TIMESTAMPTZ NOT NULL
    );

